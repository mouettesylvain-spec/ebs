# R3: result.json is written from the transcript, deterministically
def test_classify_writes_result_json(tmp_path: Path) -> None:
    result = _work(tmp_path, "uvm_error")
    rule = QuestaSimRule()
    assert rule.classify(0, "", {"result": result}) == FAILED
    doc = json.loads(result.read_text())
    assert doc == {
        "schema": 1,
        "status": "failed",
        "test": "t1",
        "seed": "7",
        "exit_code": 0,
        "finished": True,
        "uvm_errors": 2,
        "uvm_fatals": 0,
        "errors": 0,
        "fatals": 0,
        "first_error": (
            "UVM_ERROR /proj/cpu/tb/scoreboard.sv(142) @ 12500: uvm_test_top.env.sb [SCB] data "
            "mismatch at 0x1f00: expected 'h12 got 'h13"
        ),
        "signature": (
            "UVM_ERROR <path>(<n>) @ <n>: uvm_test_top.env.sb [SCB] data mismatch at <hex>: "
            "expected <hex> got <hex>"
        ),
    }
    first = result.read_bytes()
    # classifying again (the runner may retry the bookkeeping) changes nothing
    assert rule.classify(0, "", {"result": result}) == FAILED
    assert result.read_bytes() == first
    assert rule.summarize({"result": result}, tmp_path / "log") == {
        "status": "failed",
        "test": "t1",
        "seed": "7",
        "uvm_errors": 2,
        "uvm_fatals": 0,
        "errors": 0,
        "fatals": 0,
        "signature": doc["signature"],
    }


# R3: two passing runs give byte-identical result.json (early cutoff downstream)
def test_passing_result_is_deterministic(tmp_path: Path) -> None:
    docs = []
    for i in range(2):
        result = _work(tmp_path / str(i), "pass_uvm")
        assert QuestaSimRule().classify(0, "", {"result": result}) == PASSED
        docs.append(result.read_bytes())
    assert docs[0] == docs[1]
    assert json.loads(docs[0])["status"] == "passed"
    assert json.loads(docs[0])["first_error"] is None


