_PLUSARG = st.builds(
    lambda name, value: f"+{name}" + ("" if value is None else f"={value}"),
    st.from_regex(r"[A-Za-z_][A-Za-z0-9_]{0,10}", fullmatch=True),
    st.none()
    | st.text(
        alphabet=st.characters(
            exclude_categories=("Cs", "Cc"), exclude_characters="$"
        ),  # `${` would be a reference; control characters cannot appear in a YAML scalar
        max_size=12,
    ),
)


# R3: plusargs are split like a shell would and passed as single, unexpanded arguments
@given(st.lists(_PLUSARG, max_size=6))
def test_plusargs_split_safely(plusargs: list[str]) -> None:
    t = _expand(**_sim(params={"test": "t", "seed": 1, "plusargs": shlex.join(plusargs)}))
    vsim = script_commands(t.config_files[SCRIPT])[-1]
    start = vsim.index("+UVM_TESTNAME=t") + 1
    assert vsim[start : start + len(plusargs)] == plusargs
    assert vsim[start + len(plusargs) :] == ["opt"]


