def _work(tmp_path: Path, transcript: str | None, *, result: str = "result.json") -> Path:
    """A work dir as the generated script leaves it: the stub, and the transcript if any."""
    work = tmp_path / "work"
    (work / result).parent.mkdir(parents=True, exist_ok=True)
    stub = {"ebs_pending": "questa.sim", "seed": "7", "test": "t1", "result": result}
    (work / result).write_text(json.dumps(stub) + "\n")
    if transcript is not None:
        (work / "transcript").write_text((FIXTURES / f"{transcript}.txt").read_text())
    return work / result


