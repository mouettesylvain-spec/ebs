# R1
def test_modelsim_ini_maps_fanin() -> None:
    resolver = StagedResolver(
        {
            ("compile", "worklib"): ["compile[lib=b]", "compile[lib=a]"],
            ("vendor_ip", "lib"): ["vendor_ip[name=x,lib=c%5F1]"],
            ("gen", "out"): ["gen"],
        }
    )
    t = _expand(
        resolver,
        inputs={
            "filelist": "top.f",
            "deps": "${steps.compile.outputs.worklib[*]}",
            "ip": ["${steps.vendor_ip.outputs.lib[*]}", "${steps.gen.outputs.out}"],
        },
        params={"lib": "top"},
    )
    ini = t.config_files[INI].splitlines()
    assert ini[1:] == [
        "[Library]",
        "others = $MODEL_TECH/../modelsim.ini",
        "a = worklib/compile[lib=a]",
        "b = worklib/compile[lib=b]",
        "c_1 = lib/vendor_ip[name=x,lib=c%5F1]",  # percent-decoded from the action id
        "gen = out/gen",  # an unmatrixed producer is named after its step
    ]
    vlog = script_commands(t.config_files[SCRIPT])[-1]
    assert [vlog[i + 1] for i, a in enumerate(vlog) if a == "-L"] == ["a", "b", "c_1", "gen"]


