def _actual(rule: QuestaCompileRule, fields: dict[str, Any]) -> dict[str, Any]:
    s = _compile(**fields)
    t = rule.expand(s, qcontext(s, FANIN, name=_name(fields)))
    assert set(t.config_files) == {SCRIPT, INI}
    return {
        "version": rule.version,
        "argv": list(t.argv),
        "commands": script_commands(t.config_files[SCRIPT]),
        "modelsim_ini": t.config_files[INI],
        "outputs": {
            name: {"dir": out.dir, "deterministic": out.deterministic}
            for name, out in t.outputs.items()
        },
        "env": dict(t.env),
    }


