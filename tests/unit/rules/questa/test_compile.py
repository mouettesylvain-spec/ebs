def _compile(**fields: Any) -> StepDef:
    return step(kind="questa.compile", **fields)


def _name(fields: dict[str, Any]) -> str:
    # An unmatrixed compile step is named after its library (see test_lib_matches_*).
    lib = fields.get("params", {}).get("lib")
    return lib if isinstance(lib, str) and re.fullmatch(r"[a-z][a-z0-9_]*", lib) else "s"


def _expand(resolver: StagedResolver | None = None, **fields: Any) -> ActionTemplate:
    s = _compile(**fields)
    return QuestaCompileRule().expand(s, qcontext(s, resolver, name=_name(fields)))


