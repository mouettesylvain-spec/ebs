# R5: the simulator reports its own crashes as a fatal message and a plain exit status
def test_classify_crash_message() -> None:
    tail = "-- Compiling module alu\n** Fatal: (SIGSEGV) Bad handle or reference.\n"
    assert QuestaCompileRule().classify(211, tail, {}) == INFRA("tool_crash")
    assert QuestaCompileRule().classify(-signal.SIGSEGV, "", {}) == INFRA("tool_crash")


