# R1: consumers name a library after its producer, so the producer must compile it under
# that same name: the `lib` matrix value, or the step name without a matrix
def test_lib_matches_unmatrixed_step_name() -> None:
    s = _compile(inputs={"filelist": "a.f"}, params={"lib": "pkg"})
    rule = QuestaCompileRule()
    assert rule.expand(s, qcontext(s, name="pkg")).outputs["worklib"].dir == "work/pkg"
    with pytest.raises(RuleError, match=r"downstream steps will call it 'compile_pkg'"):
        rule.expand(s, qcontext(s, name="compile_pkg"))


# R1
def test_lib_matches_matrix_column() -> None:
    rule = QuestaCompileRule()
    s = _compile(
        matrix={"table": "t.csv"},
        inputs={"filelist": "${row.filelist}"},
        params={"lib": "${row.lib}"},
    )
    rows = [{"lib": "core", "filelist": "core.f"}, {"lib": "tb", "filelist": "tb.f"}]
    dirs = [rule.expand(s, c).outputs["worklib"].dir for c in qcontexts(s, rows, name="compile")]
    assert dirs == ["work/core", "work/tb"]

    renamed = _compile(
        matrix={"table": "t.csv"},
        inputs={"filelist": "${row.filelist}"},
        params={"lib": "x_${row.lib}"},
    )
    (first, _) = qcontexts(renamed, rows, name="compile")
    with pytest.raises(
        RuleError, match=r"downstream steps will call it 'core'.*lib: \$\{row.lib\}"
    ):
        rule.expand(renamed, first)

    no_column = _compile(
        matrix={"table": "t.csv"}, inputs={"filelist": "${row.f}"}, params={"lib": "core"}
    )
    (only,) = qcontexts(no_column, [{"f": "a.f"}], name="compile")
    with pytest.raises(RuleError, match=r"no 'lib' column"):
        rule.expand(no_column, only)


