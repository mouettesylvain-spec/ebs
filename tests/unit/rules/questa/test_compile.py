# R5: a missing tool is infrastructure; a crash message after a successful exit is not
def test_classify_missing_tool_and_clean_exit() -> None:
    rule = QuestaCompileRule()
    assert rule.classify(127, "bash: vlog: command not found\n", {}) == INFRA("tool_missing")
