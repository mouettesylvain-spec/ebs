"""Tests for the `questa.opt` rule (task P1-08 R2, R5, R6)."""

from __future__ import annotations

from typing import Any

import pytest

from ebs.core.errors import RuleError
from ebs.flow.model import OutputDef
from ebs.rules.api import INFRA, ActionTemplate, Classification
from ebs.rules.questa.opt import QuestaOptRule
from tests.helpers.questa import StagedResolver, qcontext, script_commands
from tests.helpers.rules import CLASSIFY_CASES, step

BASH = ("bash", "--noprofile", "--norc", "-eo", "pipefail")
SCRIPT = ".ebs/questa_opt.sh"
INI = "modelsim.ini"

LIBS = StagedResolver(
    {("compile", "worklib"): ["compile[filelist=libs%2Fcore.f,lib=core]", "compile[lib=periph]"]}
)


def _expand(resolver: StagedResolver = LIBS, **fields: Any) -> ActionTemplate:
    s = step(kind="questa.opt", **fields)
    return QuestaOptRule().expand(s, qcontext(s, resolver))


GOLDEN = {
    "version": "1",
    "argv": [*BASH, SCRIPT],
    "commands": [
        ["vlib", "opt"],
        [
            "exec",
            "vopt",
            "-modelsimini",
            INI,
            "-work",
            "opt",
            "-L",
            "core",
            "-L",
            "periph",
            "+acc=npr",
            "tb_top",
            "-o",
            "opt",
        ],
    ],
    "modelsim_ini": (
        "; Generated by ebs (rule questa.opt). Do not edit.\n"
        "[Library]\n"
        "others = $MODEL_TECH/../modelsim.ini\n"
        "core = worklib/compile[filelist=libs%2Fcore.f,lib=core]\n"
        "periph = worklib/compile[lib=periph]\n"
    ),
    "outputs": {},
}


# R2, R6
def test_argv_golden() -> None:
    rule = QuestaOptRule()
    t = _expand(
        inputs={"libs": "${steps.compile.outputs.worklib[*]}"},
        params={"top": "tb_top", "vopt_opts": "+acc=npr"},
        outputs={"model": {"dir": "opt", "deterministic": False}},
    )
    actual = {
        "version": rule.version,
        "argv": list(t.argv),
        "commands": script_commands(t.config_files[SCRIPT]),
        "modelsim_ini": t.config_files[INI],
        "outputs": dict(t.outputs),
    }
    assert actual == GOLDEN, (
        "the questa.opt rule's generated command changed: if intended, bump "
        "QuestaOptRule.version (it is part of every action key) and update GOLDEN"
    )


# R6
def test_rule_version_golden() -> None:
    rule = QuestaOptRule()
    assert (rule.kind, rule.version) == ("questa.opt", "1")


# R2: the model is a nondeterministic dir named `opt` unless the flow declares it
def test_generated_model_output() -> None:
    t = _expand(inputs={"libs": "${steps.compile.outputs.worklib[*]}"}, params={"top": "tb"})
    assert dict(t.outputs) == {"model": OutputDef(dir="opt", deterministic=False)}
    vlib, vopt = script_commands(t.config_files[SCRIPT])
    assert vlib == ["vlib", "opt"]
    assert vopt[-3:] == ["tb", "-o", "opt"]


# R2: several tops, each its own argument
def test_several_tops() -> None:
    t = _expand(
        inputs={"libs": "${steps.compile.outputs.worklib[*]}"},
        params={"top": "tb_top glbl"},
        outputs={"model": {"dir": "m", "deterministic": False}},
    )
    vopt = script_commands(t.config_files[SCRIPT])[-1]
    assert vopt[vopt.index("-work") + 1] == "m"
    assert vopt[-4:] == ["tb_top", "glbl", "-o", "opt"]


# R2
@pytest.mark.parametrize(
    ("fields", "message"),
    [
        ({"inputs": {"libs": "${steps.compile.outputs.worklib[*]}"}}, r"'top' param is required"),
        ({"params": {"top": "tb"}}, r"at least one library input"),
        (
            {"inputs": {"libs": "${steps.compile.outputs.worklib[*]}"}, "params": {"top": "-o x"}},
            r"top '-o' must be a design unit name",
        ),
        (
            {
                "inputs": {"libs": "${steps.compile.outputs.worklib[*]}"},
                "params": {"top": "tb", "opts": "x"},
            },
            r"unknown param 'opts'",
        ),
        (
            {
                "inputs": {"libs": "${steps.compile.outputs.worklib[*]}"},
                "params": {"top": "tb"},
                "outputs": {"model": {"dir": "opt"}},
            },
            r"set 'deterministic' explicitly",
        ),
    ],
)
def test_validation_errors(fields: dict[str, Any], message: str) -> None:
    with pytest.raises(RuleError, match=message):
        _expand(**fields)


# R5
@pytest.mark.parametrize(("exit_code", "log_tail", "expected"), CLASSIFY_CASES)
def test_classify(exit_code: int, log_tail: str, expected: Classification) -> None:
    assert QuestaOptRule().classify(exit_code, log_tail, {}) == expected


# R5
def test_classify_crash_message() -> None:
    assert QuestaOptRule().classify(3, "# ** Fatal: (SIGBUS) bus error\n", {}) == INFRA(
        "tool_crash"
    )


# R2
@pytest.mark.parametrize("top", ["", "  "])
def test_empty_top_rejected(top: str) -> None:
    with pytest.raises(RuleError, match=r"must be a design unit name"):
        _expand(inputs={"libs": "${steps.compile.outputs.worklib[*]}"}, params={"top": top})


# R2: generated script words are shell-quoted
def test_model_path_with_space_is_quoted() -> None:
    t = _expand(
        inputs={"libs": "${steps.compile.outputs.worklib[*]}"},
        params={"top": "tb"},
        outputs={"model": {"dir": "m x", "deterministic": False}},
    )
    vlib, vopt = script_commands(t.config_files[SCRIPT])
    assert vlib == ["vlib", "m x"]
    assert vopt[vopt.index("-work") + 1] == "m x"


# R5
def test_classify_missing_tool() -> None:
    assert QuestaOptRule().classify(127, "", {}) == INFRA("tool_missing")
