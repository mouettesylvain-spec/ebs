"""The batch script of a SLURM job: one fixed template that execs `ebs-runner` (P1-02 R3).

The script holds no flow text except argv values, each passed through `shlex.quote`, so an
action id like `sim[test=$(rm -rf ~)]` reaches the runner as one inert argument. Options (job
name, resources, output paths, `--export=NONE`) go on the sbatch command line, not in `#SBATCH`
lines; the job's environment comes from the `--export-file` only.
"""

from __future__ import annotations

import shlex
from collections.abc import Sequence
from typing import Final

from ebs.core.digest import Digest
from ebs.core.errors import ExecutorError

__all__ = ["render_jobscript", "runner_arguments"]

_TEMPLATE: Final = """\
#!/bin/bash
# Generated by ebs: runs one action (or one array task) through ebs-runner. Do not edit.
set -euo pipefail
exec {argv}
"""


def runner_arguments(
    runner_argv: Sequence[str],
    *,
    plan: Digest,
    domain: str,
    build: int | None,
    action: str | None = None,
    array_map: Digest | None = None,
) -> list[str]:
    """The `ebs-runner` command line of a job (interfaces.md § 9): one action or an array map."""
    if (action is None) == (array_map is None):
        raise ExecutorError("a job runs exactly one of: an action, or an array map")
    argv = [*runner_argv, "--plan", str(plan)]
    if action is not None:
        argv += ["--action", action]
    else:
        argv += ["--array-map", str(array_map)]
    argv += ["--domain", domain]
    if build is not None:
        argv += ["--build", str(build)]
    return argv


def render_jobscript(argv: Sequence[str]) -> str:
    """The batch script that execs `argv` (every element shell-quoted)."""
    if not argv:
        raise ExecutorError("the job script needs a command to run; runner_argv is empty")
    for arg in argv:
        if "\x00" in arg:
            raise ExecutorError(f"cannot put {arg!r} on a command line: it contains a NUL byte")
    return _TEMPLATE.format(argv=" ".join(shlex.quote(a) for a in argv))
