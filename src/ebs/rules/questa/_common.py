TOOL_MISSING_EXITS: Final = frozenset({126, 127})
"""bash's "cannot execute" / "command not found": the tool is missing on this node (a module not
loaded, an automount not ready). Infrastructure, like a runner that cannot start the tool: a
FAILED result would be cached for every node."""


def script(kind: str, commands: Sequence[Sequence[str]], *, prelude: Iterable[str] = ()) -> str:
    """A bash script running `commands` in order; the last one is `exec`ed, so the tool's own
    exit status (or signal) is the action's. Every word is shell-quoted."""
    lines = [f"# Generated by ebs (rule {kind}). Do not edit.", *prelude]
    lines += [shlex.join(cmd) for cmd in commands[:-1]]
    lines.append("exec " + shlex.join(commands[-1]))
    return "\n".join(lines) + "\n"


def script_path(kind: str) -> str:
    return f"{GENERATED_DIR}/{kind.replace('.', '_')}.sh"


def script_argv(kind: str) -> tuple[str, ...]:
    return (*BASH_ARGV, script_path(kind))


def split_opts(value: ParamValue, name: str, instance_id: str) -> list[str]:
    """Split an options param like a shell would (quotes group, nothing is expanded)."""
    try:
        return shlex.split(param_text(value))
    except ValueError as exc:
        raise RuleError(
            f"step {instance_id!r}: param {name} {param_text(value)!r} cannot be split into "
            f"arguments: {exc}; balance the quotes"
        ) from None


@dataclass(frozen=True)
class StepInputs:
    """A step's inputs, rendered: `refs` are staged step outputs, `sources` source patterns."""

    refs: dict[str, list[str]]
    sources: dict[str, list[str]]

    def libraries(self, exclude: Iterable[str] = ()) -> list[str]:
        skip = set(exclude)
        return [p for name, paths in self.refs.items() if name not in skip for p in paths]


def step_inputs(step: StepDef, ctx: ExpandContext) -> StepInputs:
    refs: dict[str, list[str]] = {}
    sources: dict[str, list[str]] = {}
    for name, value in step.inputs.items():
        texts = (value,) if isinstance(value, str) else value
        for i, text in enumerate(texts):
            field = f"inputs.{name}" if isinstance(value, str) else f"inputs.{name}[{i}]"
            is_ref = any(
                isinstance(p, Ref) and p.kind == "steps" for p in parse_template(text).parts
            )
            rendered = ctx.render(text, field=field)
            paths = rendered if isinstance(rendered, list) else [rendered]
            (refs if is_ref else sources).setdefault(name, []).extend(paths)
    return StepInputs(refs, sources)


def check_params(kind: str, step: StepDef, allowed: Sequence[str], required: Sequence[str]) -> None:
    for name in step.params:
        if name not in allowed:
            close = difflib.get_close_matches(name, allowed, n=1, cutoff=0.6)
            hint = f"did you mean {close[0]!r}? " if close else ""
            raise RuleError(
                f"a {kind!r} step has unknown param {name!r}: {hint}"
                f"its params are {', '.join(allowed)}"
            )
    for name in required:
        if name not in step.params:
            raise RuleError(f"a {kind!r} step's {name!r} param is required")


def declared_or_default_output(
    kind: str,
    step: StepDef,
    ctx: ExpandContext,
    name: str,
    default: OutputDef,
) -> tuple[str, dict[str, OutputDef]]:
    """The work-dir path of output `name`, and the outputs to generate (none if declared).

    A declared output must have the default's type; a declared directory must set
    `deterministic` explicitly, since Questa libraries embed timestamps.
    """
    is_dir = default.dir is not None
    declared = step.outputs.get(name)
    if declared is None:
        path = default.dir if is_dir else default.file
        assert path is not None
        return path, {name: default}
    raw = declared.dir if is_dir else declared.file
    if raw is None:
        raise RuleError(
            f"a {kind!r} step's output {name!r} must be a {'directory' if is_dir else 'file'} "
            f"({'dir' if is_dir else 'file'}: <path>)"
        )
    if is_dir and "deterministic" not in declared.model_fields_set:
        raise RuleError(
            f"a {kind!r} step's output {name!r} must set 'deterministic' explicitly: Questa "
            "libraries embed timestamps, so use 'deterministic: false' (or omit the output "
            "and ebs generates it that way)"
        )
    return ctx.render_str(raw, field=f"outputs.{name}"), {}


class QuestaRule(BaseRule):
    """Default classification, plus the tools' own crash reports (`** Fatal: (SIGSEGV)`)."""

    allowed_params: tuple[str, ...] = ()
    required_params: tuple[str, ...] = ()

    def validate(self, step: StepDef) -> None:
        self._reject_fields(
            step,
            ("script", "command", "workdir", "target"),
            "the command line is generated from its inputs and params",
        )
        check_params(self.kind, step, self.allowed_params, self.required_params)

    def classify(
        self, exit_code: int, log_tail: str, outputs: Mapping[str, Path]
    ) -> Classification:
        classification = super().classify(exit_code, log_tail, outputs)
        if classification.status != "failed":
            return classification
        if exit_code in TOOL_MISSING_EXITS:
            return INFRA("tool_missing")
        if parse_transcript(log_tail.splitlines()).crashed:
            return INFRA("tool_crash")
        return classification
