"""`modelsim.ini` generation and logical names of upstream (fan-in) libraries.

The planner stages an upstream output at `<output>/<producer action id>` (P0-08), e.g.
`worklib/compile[lib=core]`. Questa refers to libraries by logical name, so each staged library
needs one, and it must be the same in every consumer: dependencies recorded in a compiled
library name the libraries they came from. The name is the producer's `lib` matrix value
(`compile[lib=core]` -> `core`), or the producer's step name when it has no matrix (`ip` -> `ip`).
"""

from __future__ import annotations

import re
from collections.abc import Iterable, Mapping
from typing import Final
from urllib.parse import unquote

from ebs.core.errors import RuleError

__all__ = [
    "LIBRARY_NAME_PATTERN",
    "MODELSIM_INI",
    "RESERVED_LIBRARY_NAMES",
    "check_library_name",
    "fanin_libraries",
    "library_name",
    "modelsim_ini",
]

MODELSIM_INI: Final = "modelsim.ini"
"""At the work-dir root, not under `.ebs/`: Questa resolves relative library paths in an ini
against the ini's own directory, which is then the same as the tools' working directory."""

LIBRARY_NAME_PATTERN: Final = r"[A-Za-z][A-Za-z0-9_]*"
RESERVED_LIBRARY_NAMES: Final = frozenset({"work", "others"})
"""`work` is the compiling library's own alias; `others` is the ini key that includes the
installation's modelsim.ini (standard libraries)."""

_NAME_RE = re.compile(LIBRARY_NAME_PATTERN)
_ACTION_ID_RE = re.compile(r"(?P<step>[a-z][a-z0-9_]*)(?:\[(?P<pairs>[^\[\]]*)\])?")
_INI_UNSAFE = re.compile(r"[\x00-\x1f\x7f;$]")


def check_library_name(name: str, what: str) -> str:
    if not _NAME_RE.fullmatch(name) or name.lower() in RESERVED_LIBRARY_NAMES:
        raise RuleError(
            f"{what} {name!r} is not a valid library name: use a letter, then letters, digits or "
            f"'_' (not {' or '.join(sorted(RESERVED_LIBRARY_NAMES))})"
        )
    return name


def library_name(staged_path: str) -> str:
    """The logical name of the upstream library staged at `staged_path`."""
    _, _, producer = staged_path.partition("/")
    m = _ACTION_ID_RE.fullmatch(producer)
    if m is None:
        raise RuleError(
            f"cannot name the library input {staged_path!r}: it is not a staged step output; "
            "library inputs must be ${steps.<step>.outputs.<output>…} references"
        )
    if m["pairs"] is None:
        name = m["step"]
    else:
        pairs = dict(pair.partition("=")[::2] for pair in m["pairs"].split(","))
        if "lib" not in pairs:
            raise RuleError(
                f"cannot name the upstream library staged at {staged_path!r}: its producer "
                f"{producer!r} has no 'lib' column; add a 'lib' column to that step's matrix "
                "table (and to 'matrix.id' if you set it): its value is the library's name"
            )
        name = unquote(pairs["lib"], errors="strict")
    return check_library_name(name, f"the library name of {staged_path!r},")


def fanin_libraries(staged_paths: Iterable[str]) -> dict[str, str]:
    """Logical name -> staged path, sorted by name; two libraries with one name are an error."""
    libraries: dict[str, str] = {}
    for path in staged_paths:
        name = library_name(path)
        other = libraries.setdefault(name, path)
        if other != path:
            raise RuleError(
                f"two upstream libraries are named {name!r} ({other!r} and {path!r}); "
                "give their producers distinct 'lib' values"
            )
    return dict(sorted(libraries.items()))


def modelsim_ini(kind: str, libraries: Mapping[str, str]) -> str:
    """A modelsim.ini mapping each library to its path in the work dir.

    `others` includes the installation's own modelsim.ini (`$MODEL_TECH` is set by the tools),
    so the standard libraries (std, ieee, …) resolve as usual.
    """
    lines = [
        f"; Generated by ebs (rule {kind}). Do not edit.",
        "[Library]",
        "others = $MODEL_TECH/../modelsim.ini",
    ]
    for name, path in libraries.items():
        if _INI_UNSAFE.search(path):
            raise RuleError(
                f"library {name!r} path {path!r} holds a character modelsim.ini cannot carry "
                "(control characters, ';' or '$'); rename the producing step or its matrix values"
            )
        lines.append(f"{name} = {path}")
    return "\n".join(lines) + "\n"
