# --- Markdown helpers ---------------------------------------------------------------------------


def md_text(text: str) -> str:
    """Plain text for a table cell: no HTML, no column breaks, one line."""
    escaped = text.replace("<", "&lt;").replace(">", "&gt;").replace("|", r"\|")
    return " ".join(escaped.split())


def md_prose(text: str) -> str:
    """Docstring or help text as Markdown: `<` and `>` escaped outside code spans."""
    out, pos = [], 0
    for m in _CODE_SPAN.finditer(text):
        out.append(text[pos : m.start()].replace("<", "&lt;").replace(">", "&gt;"))
        out.append(m.group())
        pos = m.end()
    out.append(text[pos:].replace("<", "&lt;").replace(">", "&gt;"))
    return "".join(out)


def frontmatter(title: str, description: str, *, order: int | None = None) -> str:
    lines = ["---", f"title: {json.dumps(title)}", f"description: {json.dumps(description)}"]
    lines.append("editUrl: false")
    if order is not None:
        lines += ["sidebar:", f"  order: {order}"]
    return "\n".join([*lines, "---", ""])


def page(title: str, description: str, source: str, body: str, *, order: int | None = None) -> str:
    note = GENERATED_NOTE.format(source=source)
    return (
        f"{frontmatter(title, description, order=order)}\n:::note\n{note}\n:::\n\n{body.strip()}\n"
    )


def table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + " --- |" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


# --- CLI ----------------------------------------------------------------------------------------


# Typer bundles its own click (typer._click), so commands and params are duck-typed here.
Command = Any
Param = Any


def is_group(cmd: Command) -> bool:
    return isinstance(getattr(cmd, "commands", None), dict)


def is_option(param: Param) -> bool:
    return bool(param.param_type_name == "option")


def context(cmd: Command, name: str) -> Any:
    return cmd.context_class(cmd, info_name=name)


@dataclass(frozen=True)
class CommandDoc:
    path: tuple[str, ...]
    command: Command


def iter_commands(group: Command, prefix: tuple[str, ...] = ()) -> Iterator[CommandDoc]:
    """Every leaf command below `group`, depth first, in registration order."""
    if not is_group(group):
        yield CommandDoc(prefix, group)
        return
    for name, sub in group.commands.items():
        if not sub.hidden:
            yield from iter_commands(sub, (*prefix, name))


def _first_line(text: str | None) -> str:
    return (text or "").strip().split("\n\n")[0].replace("\n", " ")


def _param_row(param: Param, ctx: Any) -> list[str]:
    if is_option(param):
        names = ", ".join(f"`{o}`" for o in [*param.opts, *param.secondary_opts])
        value = "" if param.is_flag else f" `{param.make_metavar(ctx).replace('|', chr(92) + '|')}`"
        help_text = param.help or ""
        default = param.default
        if not param.is_flag and default not in (None, (), [], "") and not callable(default):
            help_text += f" Default: `{default}`."
    else:
        names, value = f"`{param.human_readable_name}`", ""
        help_text = getattr(param, "help", None) or ""
    required = "yes" if param.required else ""
    return [names + value, required, md_text(help_text)]


def render_command(doc: CommandDoc) -> str:
    cmd = doc.command
    ctx = context(cmd, " ".join(["ebs", *doc.path]))
    usage = " ".join(cmd.collect_usage_pieces(ctx))
    parts = [f"## `ebs {' '.join(doc.path)}`", "", md_prose((cmd.help or "").strip()), ""]
    parts += ["```text", f"ebs {' '.join(doc.path)} {usage}".rstrip(), "```", ""]
    params = [p for p in cmd.params if not getattr(p, "hidden", False)]
    if params:
        rows = [_param_row(p, ctx) for p in params]
        parts += [table(["Argument / option", "Required", "Description"], rows), ""]
    return "\n".join(parts)


def json_note(root: Command) -> str:
    """Which commands take `--json`, from the app itself (so the sentence cannot go stale)."""
    without = [
        f"`ebs {' '.join(doc.path)}`"
        for doc in iter_commands(root)
        if not any("--json" in getattr(p, "opts", ()) for p in doc.command.params)
    ]
    if not without:
        return "Every command takes `--json` (machine-readable output) and honours `NO_COLOR`. "
    return (
        "Every command except " + ", ".join(without) + " takes `--json` (machine-readable "
        "output); all honour `NO_COLOR`. "
    )


def render_cli(app: typer.Typer) -> dict[str, str]:
    """File name -> page: `index.md` plus one page per top-level command or group."""
    root: Command = typer.main.get_command(app)
    assert is_group(root)
    source = "`src/ebs/cli/`"
    pages: dict[str, str] = {}
    rows = []
    for order, (name, sub) in enumerate(root.commands.items(), start=1):
        if sub.hidden:
            continue
        link = f"[`ebs {name}`]({BASE}/reference/cli/{name}/)"
        rows.append([link, md_text(_first_line(sub.help))])
        body = [md_prose((sub.help or "").strip()), ""]
        body += [render_command(doc) for doc in iter_commands(sub, (name,))]
        pages[f"{name}.md"] = page(
            f"ebs {name}", _first_line(sub.help) or f"The ebs {name} command.", source,
            "\n".join(body), order=order,
        )  # fmt: skip
    ctx = context(root, "ebs")
    global_rows = [_param_row(p, ctx) for p in root.params if not getattr(p, "hidden", False)]
    index = [
        md_prose(root.help or ""),
        "",
        json_note(root),
        f"Exit codes are listed in [Exit codes]({BASE}/reference/exit-codes/).",
        "",
        "## Global options",
        "",
        table(["Option", "Required", "Description"], global_rows),
        "",
        "## Commands",
        "",
        table(["Command", "Summary"], rows),
    ]
    pages["index.md"] = page(
        "CLI reference", "Every ebs command, argument and option.", source, "\n".join(index),
        order=0,
    )  # fmt: skip
    return pages


# --- Python API ---------------------------------------------------------------------------------


def public_names(module: ModuleType) -> list[str]:
    """`__all__`, else the names defined in the module that do not start with `_`."""
    names = getattr(module, "__all__", None)
    if names is not None:
        return list(names)
    return [
        name
        for name, value in vars(module).items()
        if not name.startswith("_")
        and getattr(value, "__module__", None) == module.__name__
        and (inspect.isclass(value) or inspect.isfunction(value))
    ]


def _signature(name: str, obj: object) -> str | None:
    try:
        sig = inspect.signature(obj)  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return None
    text = str(sig).replace("'", "")
    if inspect.isclass(obj):
        return f"class {name}{text}"
    return f"def {name}{text}"


def attribute_docs(module: ModuleType) -> dict[str, str]:
    """Docstrings written under module-level assignments (`NAME = …` then a string literal)."""
    docs: dict[str, str] = {}
    body = ast.parse(inspect.getsource(module)).body
    for node, after in itertools.pairwise(body):
        if not isinstance(node, (ast.Assign, ast.AnnAssign)):
            continue
        targets = node.targets if isinstance(node, ast.Assign) else [node.target]
        is_doc = isinstance(after, ast.Expr) and isinstance(after.value, ast.Constant)
        doc = after.value.value if is_doc else None  # type: ignore[attr-defined]
        if isinstance(doc, str):
            for target in targets:
                if isinstance(target, ast.Name):
                    docs[target.id] = inspect.cleandoc(doc)
    return docs


def _value_text(name: str, obj: object) -> str:
    text = re.sub(r"\b(?:[a-z_][a-z0-9_]*\.)+(?=[A-Za-z_])", "", repr(obj))
    return f"{name} = {text}" if len(text) <= 300 else f"{name} = …  # {type(obj).__name__}"


def render_symbol(module: ModuleType, name: str, attr_docs: Mapping[str, str]) -> str:
    obj = getattr(module, name)
    parts = [f"### `{name}`", ""]
    is_code = inspect.isclass(obj) or inspect.isroutine(obj)
    sig = _signature(name, obj) if is_code else None
    parts += ["```python", sig or _value_text(name, obj), "```", ""]
    doc = inspect.getdoc(obj) if is_code else attr_docs.get(name)
    if doc:
        parts += [md_prose(doc), ""]
    if inspect.isclass(obj):
        methods = [
            (m, v)
            for m, v in vars(obj).items()
            if not m.startswith("_") and (inspect.isfunction(v) or isinstance(v, classmethod))
        ]
        for method, value in methods:
            func = value.__func__ if isinstance(value, classmethod) else value
            msig = _signature(method, func)
            line = f"- `{msig.removeprefix('def ') if msig else method}`"
            mdoc = inspect.getdoc(func)
            parts.append(line + (f": {md_prose(mdoc.splitlines()[0])}" if mdoc else ""))
        if methods:
            parts.append("")
    return "\n".join(parts)


def interfaces_section(text: str, number: int) -> str:
    """The body of `## <number>. …` in docs/design/interfaces.md, without its heading."""
    match = re.search(rf"^## {number}\. .*$", text, re.MULTILINE)
    if match is None:
        raise ValueError(f"docs/design/interfaces.md has no § {number}")
    rest = text[match.end() + 1 :]
    end = re.search(r"^## ", rest, re.MULTILINE)
    return (rest[: end.start()] if end else rest).strip("\n") + "\n"


def render_api_page(*, title: str, description: str, modules: Sequence[str], contract: str) -> str:
    parts = [
        "## Contract",
        "",
        f"From [docs/design/interfaces.md]({REPO_URL}/blob/main/docs/design/interfaces.md), "
        "the reviewed contract: a change here needs a `CONTRACT CHANGE` note in the commit.",
        "",
        contract,
    ]
    for name in modules:
        module = importlib.import_module(name)
        parts += [f"## `{name}`", ""]
        doc = inspect.getdoc(module)
        if doc:
            parts += [md_prose(doc), ""]
        attr_docs = attribute_docs(module)
        parts += [render_symbol(module, symbol, attr_docs) for symbol in public_names(module)]
    sources = ", ".join(f"`{m}`" for m in modules)
    return page(title, description, f"{sources} and docs/design/interfaces.md", "\n".join(parts))


# --- flow schema --------------------------------------------------------------------------------


def schema_type(node: Mapping[str, Any]) -> str:
    """A short, readable type for a JSON Schema node."""
    if "$ref" in node:
        name = node["$ref"].rsplit("/", 1)[-1]
        return f"[{name}](#{name.lower()})"
    if "enum" in node:
        return " \\| ".join(f"`{json.dumps(v)}`" for v in node["enum"])
    for key in ("anyOf", "oneOf"):
        if key in node:
            kinds = [schema_type(n) for n in node[key]]
            return " or ".join(dict.fromkeys(kinds))  # unique, in order
    kind = node.get("type")
    if kind == "array":
        return f"list of {schema_type(node.get('items', {}))}"
    if kind == "object":
        values = node.get("patternProperties") or {}
        if values:
            (pattern, value), *_ = values.items()
            return f"map `{md_text(pattern)}` → {schema_type(value)}"
        extra = node.get("additionalProperties")
        if isinstance(extra, dict):
            return f"map of {schema_type(extra)}"
        return "object"
    if isinstance(kind, list):
        return " or ".join(f"`{k}`" for k in kind)
    return f"`{kind}`" if kind else "any"


def _schema_rows(node: Mapping[str, Any]) -> list[list[str]]:
    required = set(node.get("required", ()))
    rows = []
    for name, prop in node.get("properties", {}).items():
        notes = []
        if "pattern" in prop:
            notes.append(f"pattern `{md_text(prop['pattern'])}`")
        if "default" in prop and not isinstance(prop["default"], (dict, list, type(None))):
            notes.append(f"default `{md_text(json.dumps(prop['default']))}`")
        if prop.get("description"):
            notes.insert(0, md_text(prop["description"]))
        rows.append(
            [f"`{name}`", schema_type(prop), "yes" if name in required else "", "; ".join(notes)]
        )
    return rows


def render_schema(schema: Mapping[str, Any]) -> str:
    header = ["Key", "Type", "Required", "Notes"]
    parts = [
        "The JSON Schema of `flow.yaml`, version 1. Point your editor at "
        f"[`{BASE}/schemas/flow.v1.schema.json`]({BASE}/schemas/flow.v1.schema.json) for "
        f"completion and validation (see [VS Code]({BASE}/integrations/vscode/)).",
        "",
        "## Flow file",
        "",
        md_prose(schema.get("description", "")),
        "",
        table(header, _schema_rows(schema)),
        "",
    ]
    for name, node in schema.get("$defs", {}).items():
        parts += [f"## {name}", "", md_prose(node.get("description", "")), ""]
        if node.get("properties"):
            parts += [table(header, _schema_rows(node)), ""]
        elif "anyOf" in node or "oneOf" in node:
            parts += [f"One of: {schema_type(node)}", ""]
    return page(
        "Flow schema", "Every key of flow.yaml, generated from the JSON Schema.",
        f"`{SCHEMA_FILE.as_posix()}`", "\n".join(parts), order=1,
    )  # fmt: skip


# --- site configuration, exit codes -------------------------------------------------------------


def markdown_section(text: str, heading: str) -> str:
    match = re.search(rf"^## {re.escape(heading)}.*$", text, re.MULTILINE)
    if match is None:
        raise ValueError(f"no section '## {heading}'")
    rest = text[match.end() + 1 :]
    end = re.search(r"^## ", rest, re.MULTILINE)
    return (rest[: end.start()] if end else rest).strip("\n") + "\n"


def render_config(overview: str) -> str:
    body = markdown_section(overview, "Site configuration (`ebs.toml`)")
    intro = (
        "Every key `ebs`, `ebs-runner`, the metadata service and the GC read, with its default. "
        "Comments name the task that introduced a key."
    )
    return page(
        "Site configuration (ebs.toml)", "Every ebs.toml key with its default.",
        "docs/design/overview.md § Site configuration", f"{intro}\n\n{body}", order=2,
    )  # fmt: skip


def _error_classes() -> list[type[BaseException]]:
    """The documented error hierarchy: the `EbsError` subclasses of `ebs.core.errors`."""
    from ebs.core import errors

    return [
        cls
        for cls in vars(errors).values()
        if inspect.isclass(cls) and issubclass(cls, errors.EbsError) and cls is not errors.EbsError
    ]


def render_exit_codes() -> str:
    from ebs.cli._output import exit_code_for
    from ebs.core.errors import ExitCode

    by_code: dict[ExitCode, list[str]] = {}
    for cls in _error_classes():
        by_code.setdefault(exit_code_for(cls.__new__(cls)), []).append(f"`{cls.__name__}`")
    meaning = {
        ExitCode.OK: "Success.",
        ExitCode.ACTIONS_FAILED: "The build finished and some actions failed (test failures).",
        ExitCode.INTERNAL: "A bug in ebs: the message asks you to report it.",
        ExitCode.CANCELLED: "Interrupted (Ctrl-C).",
    }
    rows = []
    for code in ExitCode:
        errors = ", ".join(sorted(by_code.get(code, [])))
        text = meaning.get(code, "")
        if errors and code != ExitCode.INTERNAL:
            text = (text + " " if text else "") + f"Raised for {errors}."
        rows.append([str(int(code)), f"`{code.name}`", text])
    body = [
        "Errors print one line on stderr, `ebs: error: <message>`; with `--json`, stdout also "
        'gets `{"error": {...}, "exit_code": N}`. A flow error message starts with '
        "`file:line:col`.",
        "",
        table(["Code", "Name", "Meaning"], rows),
    ]
    return page(
        "Exit codes", "What each ebs exit code means.",
        "`ebs.core.errors` and `ebs.cli._output.exit_code_for`", "\n".join(body), order=3,
    )  # fmt: skip


# --- roadmap ------------------------------------------------------------------------------------


@dataclass(frozen=True)
class Task:
    id: str
    title: str
    status: str


@dataclass(frozen=True)
class Phase:
    title: str
    exit: str
    tasks: tuple[Task, ...]


_PHASE = re.compile(r"^## (?P<title>.+?)(?: \(exit: (?P<exit>.*)\))?\s*$")


def parse_roadmap(readme: str) -> list[Phase]:
    """The task tables of docs/tasks/README.md: one phase per `##` heading with a task table."""
    phases: list[Phase] = []
    title = exit_ = ""
    tasks: list[Task] = []

    def close() -> None:
        if tasks:
            phases.append(Phase(title, exit_, tuple(tasks)))

    for line in readme.splitlines():
        heading = _PHASE.match(line)
        if heading:
            close()
            title, exit_, tasks = heading["title"], heading["exit"] or "", []
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if line.startswith("|") and len(cells) >= 5 and re.fullmatch(r"[A-Z]\d*-\d+\w*", cells[0]):
            tasks.append(Task(cells[0], cells[1], cells[-1]))
    close()
    return phases


def render_roadmap(readme: str) -> str:
    parts = [
        "What is shipped and what is planned, straight from the task index. Only shipped "
        "features are documented on this site.",
        "",
    ]
    for phase in parse_roadmap(readme):
        done = sum(t.status == "done" for t in phase.tasks)
        parts += [f"## {phase.title}", ""]
        summary = f"**{done} of {len(phase.tasks)} done.**"
        if phase.exit:
            summary += f" Exit criterion: {md_prose(phase.exit)}."
        parts += [summary, ""]
        rows = [
            [
                t.id,
                md_text(t.title),
                f'<span class="ebs-status" data-status="{t.status}">{t.status}</span>',
            ]
            for t in phase.tasks
        ]
        parts += [table(["Task", "Title", "Status"], rows), ""]
    return page(
        "Roadmap", "Shipped and planned work, from the task index.", "docs/tasks/README.md",
        "\n".join(parts), order=9,
    )  # fmt: skip


# --- driver -------------------------------------------------------------------------------------


def generate(repo: Path, out: Path, public: Path) -> list[Path]:
    """Write every reference page under `out` (emptied first) and the schema under `public`."""
    from ebs.cli.main import app

    interfaces = (repo / "docs" / "design" / "interfaces.md").read_text(encoding="utf-8")
    pages: dict[str, str] = {f"cli/{name}": text for name, text in render_cli(app).items()}
    schema = json.loads((repo / SCHEMA_FILE).read_text(encoding="utf-8"))
    pages["flow-schema.md"] = render_schema(schema)
    pages["config.md"] = render_config(
        (repo / "docs" / "design" / "overview.md").read_text(encoding="utf-8")
    )
    pages["rule-api.md"] = render_api_page(
        title="Rule plugin API",
        description="Write step kinds: the RulePlugin protocol and its helpers.",
        modules=RULE_MODULES,
        contract=interfaces_section(interfaces, 7),
    )
    pages["toolchain-api.md"] = render_api_page(
        title="Toolchain API",
        description="Toolchain ids, fingerprints, module snapshots and the registry.",
        modules=TOOLCHAIN_MODULES,
        contract=interfaces_section(interfaces, 13),
    )
    pages["exit-codes.md"] = render_exit_codes()
    pages["roadmap.md"] = render_roadmap(
        (repo / "docs" / "tasks" / "README.md").read_text(encoding="utf-8")
    )

    if out.exists():
        shutil.rmtree(out)
    written = []
    for rel, text in sorted(pages.items()):
        path = out / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        written.append(path)
    schema_out = public / "schemas" / SCHEMA_FILE.name
    schema_out.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(repo / SCHEMA_FILE, schema_out)
    written.append(schema_out)
    return written


def main(argv: Sequence[str] | None = None) -> int:
    repo_default = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0] if __doc__ else None)
    parser.add_argument("--repo", type=Path, default=repo_default)
    parser.add_argument(
        "--out", type=Path, default=None, help="default: <repo>/site/src/content/docs/reference"
    )
    parser.add_argument("--public", type=Path, default=None, help="default: <repo>/site/public")
    args = parser.parse_args(argv)
    repo: Path = args.repo
    out = args.out or repo / "site" / "src" / "content" / "docs" / "reference"
    public = args.public or repo / "site" / "public"
    written = generate(repo, out, public)
    sys.stderr.write(f"gen_site_reference: wrote {len(written)} files under {out} and {public}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
