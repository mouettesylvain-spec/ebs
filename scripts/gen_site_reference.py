"""Generate the reference section of the documentation site from the repository (task D-01).

Usage: python scripts/gen_site_reference.py [--repo DIR] [--out DIR] [--public DIR]

Writes Markdown pages into `site/src/content/docs/reference/` (gitignored, regenerated by the
site's `predev`/`prebuild` hooks) and copies the flow JSON Schema to `site/public/schemas/`, so
editors can point at a stable URL. Every page is derived from code or design docs:

- `cli/*.md`          the Typer app of `ebs.cli.main` (commands, arguments, options)
- `flow-schema.md`    schemas/flow.v1.schema.json
- `config.md`         docs/design/overview.md § Site configuration
- `rule-api.md`       `ebs.rules.api`, `ebs.rules.registry` + docs/design/interfaces.md § 7
- `toolchain-api.md`  `ebs.toolchain.*` + docs/design/interfaces.md § 13
- `exit-codes.md`     `ebs.core.errors.ExitCode` and the error classes each code covers
- `roadmap.md`        the task tables of docs/tasks/README.md

To change a page, change its source (docstrings, help texts, design docs), never the output.
"""

